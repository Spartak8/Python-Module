from ex1 import HealingCreatureFactory, TransformCreatureFactory
from ex1 import HealCapability, TransformCapability


h_fac = HealingCreatureFactory()
base = h_fac.create_base()
evolved = h_fac.create_evolved()
assert isinstance(base, HealCapability)
assert isinstance(evolved, HealCapability)
print("Testing Creature with healing capability")
print(" base:")
print(base.describe())
print(base.attack())
print(base.heal())
print(" evolved:")
print(evolved.describe())
print(evolved.attack())
print(evolved.heal())
print()

t_fac = TransformCreatureFactory()
base = t_fac.create_base()
evolved = t_fac.create_evolved()
assert isinstance(base, TransformCapability)
assert isinstance(evolved, TransformCapability)
print("Testing Creature with transform capability")
print(" base:")
print(base.describe())
print(base.attack())
print(base.transform())
print(base.attack())
print(base.revert())
print(" evolved:")
print(evolved.describe())
print(evolved.attack())
print(evolved.transform())
